// POST create a new approved site.
// Site code is generated by the backend; the frontend need not send it.
router.post(
  '/',
  authenticate,
  authorize('admin', 'manager'),
  async (req, res) => {
    let connection;

    try {
 const {
  name,
  type,
  address,
  town,
  latitude,
  longitude,
  geo_radius_m,
  notes
} = req.body;

      if (!name || !String(name).trim()) {
        return res.status(400).json({
          success: false,
          message: 'Site name is required.'
        });
      }

      connection = await pool.getConnection();
      await connection.beginTransaction();

      const site_code = await getNextSiteCode(connection);
      const dateColumns =
        await getSiteDateColumnSupport(connection);

     const fields = [
  'site_code',
  'name',
  'type',
  'address',
  'town',
  'latitude',
  'longitude',
  'geo_radius_m',
  'status',
  'notes'
];

const values = [
  site_code,
  String(name).trim(),
  type ? String(type).trim() : null,
  address || null,
  town || null,
  latitude ?? null,
  longitude ?? null,
  geo_radius_m ?? 150,
  'approved',
  notes || null
];

      if (dateColumns.has('approved_at')) {
        fields.push('approved_at');
        values.push(new Date());
      }

      const placeholders = fields.map(() => '?').join(', ');

      const [result] = await connection.query(
        `INSERT INTO sites (${fields.join(', ')})
         VALUES (${placeholders})`,
        values
      );

      await connection.commit();

      res.status(201).json({
        success: true,
        message: 'Site added and approved.',
        data: {
          id: result.insertId,
          site_code,
          name: String(name).trim(),
          status: 'approved'
        }
      });
    } catch (err) {
      if (connection) {
        await connection.rollback();
      }

      if (err.code === 'ER_DUP_ENTRY') {
        return res.status(409).json({
          success: false,
          message: 'A site code conflict occurred. Please try again.'
        });
      }

      console.error(err);
      res.status(500).json({
        success: false,
        message: 'Failed to add site.'
      });
    } finally {
      if (connection) {
        connection.release();
      }
    }
  }
);

// PUT update site details.
router.put(
  '/:id',
  authenticate,
  authorize('admin', 'manager'),
  async (req, res) => {
    try {
      if (!(await requireCurrentPassword(req, res))) return;

      const {
        name,
        type,
        address,
        town,
        latitude,
        longitude,
        geo_radius_m,
        notes
      } = req.body;

      const updates = [];
      const params = [];

      if (name !== undefined) {
        if (!String(name).trim()) {
          return res.status(400).json({
            success: false,
            message: 'Site name cannot be blank.'
          });
        }

        updates.push('name = ?');
        params.push(String(name).trim());
      }
      if (type !== undefined) {
  updates.push('type = ?');
  params.push(type ? String(type).trim() : null);
}

      if (address !== undefined) {
        updates.push('address = ?');
        params.push(address || null);
      }

      if (town !== undefined) {
        updates.push('town = ?');
        params.push(town || null);
      }

      if (latitude !== undefined) {
        updates.push('latitude = ?');
        params.push(latitude ?? null);
      }

      if (longitude !== undefined) {
        updates.push('longitude = ?');
        params.push(longitude ?? null);
      }

      if (geo_radius_m !== undefined) {
        updates.push('geo_radius_m = ?');
        params.push(geo_radius_m ?? 150);
      }

      if (notes !== undefined) {
        updates.push('notes = ?');
        params.push(notes || null);
      }

      if (!updates.length) {
        return res.status(400).json({
          success: false,
          message: 'No fields to update.'
        });
      }

      params.push(req.params.id);

      const [result] = await pool.query(
        `UPDATE sites
         SET ${updates.join(', ')}
         WHERE id = ?`,
        params
      );

      if (!result.affectedRows) {
        return res.status(404).json({
          success: false,
          message: 'Site not found.'
        });
      }

      res.json({
        success: true,
        message: 'Site updated successfully.'
      });
    } catch (err) {
      console.error(err);
      res.status(500).json({
        success: false,
        message: 'Failed to update site.'
      });
    }
  }
);

// POST approve or reapprove a site.
router.post(
  '/:id/approve',
  authenticate,
  authorize('admin', 'manager'),
  async (req, res) => {
    try {
      const dateColumns = await getSiteDateColumnSupport();
      const updates = ["status = 'approved'"];

      if (dateColumns.has('approved_at')) {
        updates.push('approved_at = CURRENT_TIMESTAMP');
      }

      if (dateColumns.has('terminated_at')) {
        updates.push('terminated_at = NULL');
      }

      const [result] = await pool.query(
        `UPDATE sites
         SET ${updates.join(', ')}
         WHERE id = ?`,
        [req.params.id]
      );

      if (!result.affectedRows) {
        return res.status(404).json({
          success: false,
          message: 'Site not found.'
        });
      }

      res.json({
        success: true,
        message: dateColumns.has('approved_at')
          ? 'Site approved and approval date recorded.'
          : 'Site approved. Approval date is not stored because approved_at is absent.'
      });
    } catch (err) {
      console.error(err);
      res.status(500).json({
        success: false,
        message: 'Failed to approve site.'
      });
    }
  }
);

